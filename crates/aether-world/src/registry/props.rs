/// The properties of one block, in declaration order.
pub fn schema_of(block: u16) -> impl Iterator<Item = (&'static str, &'static [u16])> {
    let (first, count) = BLOCK_PROPS[block as usize];
    (0..count as usize).map(move |i| {
        let (name, fv, n) = PROPS[first as usize + i];
        (
            PROP_NAMES[name as usize],
            &VALUES[fv as usize..fv as usize + n as usize],
        )
    })
}

/// The property values of a state, in declaration order.
///
/// `offset` is the state's position within its block's range.
pub fn values_of(block: u16, offset: u32) -> Vec<(&'static str, &'static str)> {
    let (first, count) = BLOCK_PROPS[block as usize];
    let mut out = Vec::with_capacity(count as usize);
    let mut rem = offset;
    // Backwards: the last property varies fastest.
    for i in (0..count as usize).rev() {
        let (name, fv, n) = PROPS[first as usize + i];
        let n = n as u32;
        let v = VALUES[fv as usize + (rem % n) as usize];
        rem /= n;
        out.push((PROP_NAMES[name as usize], VALUE_STRINGS[v as usize]));
    }
    out.reverse();
    out
}

/// The full name of a block state, or `None` if the id names none.
pub fn state_name(id: u32) -> Option<String> {
    let block = *super::blocks::STATE_TO_BLOCK.get(id as usize)?;
    let name = super::blocks::BLOCKS[block as usize].0;
    let (lo, _) = super::blocks::STATE_RANGE[block as usize];
    let vals = values_of(block, id - lo);
    if vals.is_empty() {
        return Some(name.to_owned());
    }
    let mut s = String::with_capacity(name.len() + vals.len() * 12 + 2);
    s.push_str(name);
    s.push('[');
    for (i, (k, v)) in vals.iter().enumerate() {
        if i > 0 {
            s.push(',');
        }
        s.push_str(k);
        s.push('=');
        s.push_str(v);
    }
    s.push(']');
    Some(s)
}

/// The state of `block` whose properties are `props`.
///
/// Properties may be given in any order and may be partial: anything not named
/// keeps the value it has in the block's **default** state, which is what makes
/// `state("minecraft:water", &[("level", "0")])` mean what it looks like it
/// means. A name or value the block does not have is `None` rather than a
/// guess.
pub fn state_with(block: u16, props: &[(&str, &str)]) -> Option<u32> {
    let (lo, _) = super::blocks::STATE_RANGE[block as usize];
    let default_offset = super::blocks::DEFAULT_STATE[block as usize] - lo;
    let mut chosen = values_of(block, default_offset);
    for (k, v) in props {
        let slot = chosen.iter_mut().find(|(n, _)| n == k)?;
        // The value has to be one this property actually takes.
        let (_, _, _) = PROPS[0];
        let (first, count) = BLOCK_PROPS[block as usize];
        let i = (0..count as usize).find(|i| PROP_NAMES[PROPS[first as usize + i].0 as usize] == *k)?;
        let (_, fv, n) = PROPS[first as usize + i];
        let ok = (0..n as usize)
            .any(|j| VALUE_STRINGS[VALUES[fv as usize + j] as usize] == *v);
        if !ok {
            return None;
        }
        slot.1 = *v;
    }
    // Recompose the offset, mixed-radix with the last property fastest.
    let (first, count) = BLOCK_PROPS[block as usize];
    let mut offset = 0u32;
    for i in 0..count as usize {
        let (_, fv, n) = PROPS[first as usize + i];
        let n = n as u32;
        let want = chosen[i].1;
        let j = (0..n as usize)
            .find(|j| VALUE_STRINGS[VALUES[fv as usize + j] as usize] == want)?;
        offset = offset * n + j as u32;
    }
    Some(lo + offset)
}
