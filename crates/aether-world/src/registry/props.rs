//! The property schema of every block, and the state name it implies.
//!
//! A block state's full name — `minecraft:oak_stairs[facing=north,half=bottom,
//! shape=straight,waterlogged=false]` — is *derivable*, so it is derived rather
//! than stored. Writing out all 29671 of them produced 5.4 MB of Rust
//! source; the schema below is a few tens of kilobytes and reconstructs any of
//! them in a few hundred nanoseconds.
//!
//! # How a state id decomposes
//!
//! Vanilla enumerates a block's states with the **last** declared property
//! varying fastest — mixed-radix, least-significant property last. So for an
//! offset `k` within a block's range, walking the properties backwards and
//! taking `k % len` then `k /= len` recovers each value. That ordering is the
//! only reason a bare integer can be turned back into a property set at all,
//! and it is the one thing here that would break silently if it were wrong —
//! hence the round-trip test over every state.

