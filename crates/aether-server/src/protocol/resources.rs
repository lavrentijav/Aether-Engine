/// The particle id `name` has on `protocol`, if that release has it.
pub fn particle_id(protocol: i32, name: &str) -> Option<i32> {
    let group = PARTICLE_GROUPS.iter().rev().find(|g| {
        g.protocols.contains(&protocol) || g.protocols.first().is_some_and(|p| *p <= protocol)
    })?;
    group
        .particles
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, id)| *id as i32)
}

/// Whether the 1.21.11 registry has a particle by `name`.
///
/// Command parsing is pinned to 1.21.11 even when the client is older, so a
/// name only a later release has is refused here rather than accepted and
/// then silently not drawn.
pub fn particle_exists(name: &str) -> bool {
    particle_id(774, name).is_some()
}

