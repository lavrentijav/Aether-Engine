/// Whether `name` is a vanilla sound event in the 1.21.11 registry.
pub fn sound_exists(name: &str) -> bool {
    SOUND_EVENTS.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_particle_tables_are_sorted_and_cover_the_releases() {
        for group in PARTICLE_GROUPS {
            assert!(!group.protocols.is_empty());
            assert!(group.particles.windows(2).all(|w| w[0].1 < w[1].1));
        }
        assert_eq!(particle_id(774, "minecraft:flame"), Some(32));
        assert_eq!(particle_id(767, "minecraft:flame"), Some(31));
        assert_eq!(particle_id(764, "minecraft:flame"), Some(28));
        // A particle added after 1.21.11 resolves only on the release that
        // has it, and is not a valid 1.21.11 command resource.
        assert_eq!(particle_id(777, "minecraft:sulfur_cube_goo"), Some(127));
        assert!(!particle_exists("minecraft:sulfur_cube_goo"));
        assert!(particle_exists("minecraft:dust"));
        // The 1.21.11 registry calls ids 106/107 `detection`, not
        // `detected_player`; `minecraft-data` is stale on those names.
        assert_eq!(
            particle_id(774, "minecraft:trial_spawner_detection"),
            Some(106)
        );
        assert!(particle_exists("minecraft:trial_spawner_detection"));
        assert!(!particle_exists("minecraft:trial_spawner_detected_player"));
    }

    #[test]
    fn the_sound_registry_is_the_1_21_11_one() {
        assert!(sound_exists("minecraft:block.note_block.harp"));
        assert!(sound_exists("minecraft:entity.generic.explode"));
        assert!(!sound_exists("minecraft:not_a_sound"));
        assert!(SOUND_EVENTS.windows(2).all(|w| w[0] < w[1]));
    }
}
