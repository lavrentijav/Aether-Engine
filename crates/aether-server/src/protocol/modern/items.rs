/// The `minecraft:`-qualified name of an item id.
pub fn name_of(id: i32) -> Option<&'static str> {
    ITEMS_BY_ID
        .binary_search_by(|(i, _)| i.cmp(&id))
        .ok()
        .map(|i| ITEMS_BY_ID[i].1)
}

/// The item id for a `minecraft:`-qualified name.
pub fn item_id(name: &str) -> Option<i32> {
    ITEMS
        .binary_search_by(|(n, _)| (*n).cmp(name))
        .ok()
        .map(|i| ITEMS[i].1)
}

/// Items whose name differs from the block they place.
///
/// The exceptions to "an item places the block of the same name". Small and
/// hand-written because it *is* small: everything else — every stair, slab,
/// fence, door, log — matches by name and needs no entry here.
const ITEM_TO_BLOCK: [(&str, &str); 14] = [
    ("minecraft:redstone", "minecraft:redstone_wire"),
    ("minecraft:water_bucket", "minecraft:water"),
    ("minecraft:lava_bucket", "minecraft:lava"),
    ("minecraft:powder_snow_bucket", "minecraft:powder_snow"),
    ("minecraft:string", "minecraft:tripwire"),
    ("minecraft:wheat_seeds", "minecraft:wheat"),
    ("minecraft:beetroot_seeds", "minecraft:beetroots"),
    ("minecraft:melon_seeds", "minecraft:melon_stem"),
    ("minecraft:pumpkin_seeds", "minecraft:pumpkin_stem"),
    ("minecraft:carrot", "minecraft:carrots"),
    ("minecraft:potato", "minecraft:potatoes"),
    ("minecraft:sugar_cane", "minecraft:sugar_cane"),
    ("minecraft:cocoa_beans", "minecraft:cocoa"),
    ("minecraft:nether_wart", "minecraft:nether_wart"),
];

/// The block an item places, when its name differs from the block's.
pub fn block_name_for_item(item: &str) -> Option<&'static str> {
    ITEM_TO_BLOCK
        .iter()
        .find(|(i, _)| *i == item)
        .map(|(_, b)| *b)
}

/// The item that represents a *block* in a container.
///
/// Most blocks share their name with the item that places them, which is why
/// the lookup is a plain name match. The ones that do not — a door's upper
/// half, `minecraft:water`, a wall-mounted torch — have no item at all, and a
/// stash entry for one falls back to the caller's substitute rather than
/// inventing an id the client would reject.
pub fn item_for_block(block: &str) -> Option<i32> {
    item_id(block)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_two_orderings_hold_the_same_items() {
        // They are generated from one source but written out twice, so a
        // partial regeneration would leave them disagreeing — and the reverse
        // lookup would then silently name the wrong item.
        assert_eq!(ITEMS.len(), ITEMS_BY_ID.len());
        for (id, name) in ITEMS_BY_ID {
            assert_eq!(item_id(name), Some(id), "{name}");
            assert_eq!(name_of(id), Some(name));
        }
    }

    #[test]
    fn the_id_table_is_sorted_so_binary_search_is_valid() {
        for w in ITEMS_BY_ID.windows(2) {
            assert!(w[0].0 < w[1].0, "{} is not before {}", w[0].0, w[1].0);
        }
    }

    #[test]
    fn an_id_this_version_does_not_have_names_nothing() {
        assert_eq!(name_of(-1), None);
        assert_eq!(name_of(999_999), None);
    }

    #[test]
    fn the_table_is_sorted_so_binary_search_is_valid() {
        // A single out-of-order row makes lookups silently miss rather than
        // fail, which is the worst way for a generated table to be wrong.
        for w in ITEMS.windows(2) {
            assert!(w[0].0 < w[1].0, "{} is not before {}", w[0].0, w[1].0);
        }
    }

    #[test]
    fn the_ids_the_stash_window_depends_on_are_present() {
        assert_eq!(item_id("minecraft:gray_stained_glass_pane"), Some(553));
        assert_eq!(item_id("minecraft:arrow"), Some(895));
    }

    #[test]
    fn a_block_that_has_no_item_returns_nothing_rather_than_zero() {
        // `air` is item 0, so returning 0 for "not found" would be
        // indistinguishable from a real answer.
        assert_eq!(item_id("minecraft:water"), None);
        assert_eq!(item_id("minecraft:not_a_real_block"), None);
        assert_eq!(item_id("minecraft:air"), Some(0));
    }

    #[test]
    fn every_control_the_stash_window_draws_resolves_to_a_real_item() {
        // These are named as string literals a long way from here, so a typo
        // degrades silently: the slot falls back to a barrier and the window
        // still opens, just wrong. This is the only place that can catch it.
        for control in [
            "minecraft:gray_stained_glass_pane",
            "minecraft:lime_stained_glass_pane",
            "minecraft:red_stained_glass_pane",
            "minecraft:lime_concrete",
            "minecraft:barrier",
            "minecraft:arrow",
        ] {
            assert!(item_id(control).is_some(), "{control} is not an item");
        }
    }

    #[test]
    fn common_blocks_resolve_to_their_placing_item() {
        assert_eq!(item_for_block("minecraft:stone"), Some(1));
        assert_eq!(item_for_block("minecraft:cobblestone"), Some(35));
        assert_eq!(item_for_block("minecraft:oak_stairs"), Some(441));
    }
}
