//! The version compatibility layer.
//!
//! The engine's world is 1.21.11: [`BlockStateId`]s are that release's
//! flattened state ids and [`aether_world::ItemTypeId`]s its item ids. A client
//! on another release has its own numbering, and — for anything added since —
//! no block or item with that name at all. This layer answers the one question
//! every codec asks: *what does this engine object look like on that client?*
//!
//! Two things happen here, both resolved ahead of time so the wire path is a
//! single array read:
//!
//! 1. **Translation.** An engine block state becomes the same block state in
//!    the client's version (`StateRuns` below), by name and properties. A
//!    property the version lacks takes the version's default for that block.
//! 2. **Substitution.** A block the version has never had becomes the closest
//!    thing it does have (`tools/gen/compat/blocks.json`), chosen for the same
//!    collision shape and properties where one exists (`pale_oak_stairs` →
//!    `oak_stairs`, `copper_bulb` → `copper_block`), and only as a last resort
//!    stone.
//!
//! The tables are generated by `tools/gen/compat/gen.js` from PrismarineJS
//! `minecraft-data` — the same source the engine's own registry is pinned to —
//! and each carries the list of blocks that still fall back to stone, so a
//! regression is visible in `docs/KNOWN_ISSUES.md` rather than silent.
//!
//! A substitute is a disguise: it changes only what the client sees. The
//! server's own world, and every action the client sends, still refer to the
//! real engine object.

