/// The block table for 1.8.9 (protocol 47), which predates flattened states.
pub static V1_8: LegacyTable = LegacyTable {
    runs: gen::v1_8::LEGACY_RUNS,
    reverse: gen::v1_8::LEGACY_TO_ENGINE,
    stone: gen::v1_8::STONE,
};

#[cfg(test)]
mod tests {
    use super::*;

    /// Every flat version's runs are sorted, contiguous and in range.
    fn check(table: &BlockTable, states: u32, name: &str) {
        let mut expect = 0u32;
        for &(start, len, to) in table.runs {
            assert_eq!(start, expect, "{name}: runs are not contiguous");
            assert!(len > 0, "{name}: empty run");
            assert!(
                to.checked_add(len).is_some_and(|end| end <= states),
                "{name}: run {start}..{} escapes {states} states",
                start + len
            );
            expect = start + len;
        }
        assert_eq!(
            expect,
            aether_world::registry::blocks::STATE_COUNT as u32,
            "{name}"
        );
        // Air is always air, and stone never leaves the table.
        assert_eq!(table.state(aether_api::block_ids::AIR), 0, "{name}");
        assert!(table.state(aether_api::block_ids::STONE) < states, "{name}");
    }

    #[test]
    fn every_versions_table_covers_the_engine_state_space() {
        for (t, states, name) in [
            (V1_17, gen::v1_17::STATE_COUNT, "1.17"),
            (V1_18, gen::v1_18::STATE_COUNT, "1.18"),
            (V1_19, gen::v1_19::STATE_COUNT, "1.19"),
            (V1_19_3, gen::v1_19_3::STATE_COUNT, "1.19.3"),
            (V1_20_1, gen::v1_20_1::STATE_COUNT, "1.20.1"),
            (V1_21_1, gen::v1_21_1::STATE_COUNT, "1.21.1"),
            (V1_21_4, gen::v1_21_4::STATE_COUNT, "1.21.4"),
            (V1_21_9, gen::v1_21_9::STATE_COUNT, "1.21.9"),
        ] {
            check(&t, states, name);
        }
    }

    #[test]
    fn a_modded_id_falls_back_to_the_versions_stone() {
        let beyond =
            aether_world::BlockStateId(aether_world::registry::blocks::STATE_COUNT as u32 + 7);
        assert_eq!(V1_17.state(beyond), V1_17.stone);
        assert_eq!(V1_21_1.state(beyond), V1_21_1.stone);
    }

    #[test]
    fn no_rule_covered_block_falls_back_to_stone() {
        // Substitution is the whole point of J2: every release from 1.17 on has
        // a stand-in for every engine block. This prints the remaining
        // fallbacks for 1.8, which has fewer than a fifth of the modern blocks
        // and no metadata table to derive variants from, so a large list there
        // is expected; see docs/KNOWN_ISSUES.md.
        for (name, fallbacks) in [
            ("1.17", gen::v1_17::STONE_FALLBACKS),
            ("1.19", gen::v1_19::STONE_FALLBACKS),
            ("1.20.1", gen::v1_20_1::STONE_FALLBACKS),
            ("1.21.1", gen::v1_21_1::STONE_FALLBACKS),
            ("1.21.4", gen::v1_21_4::STONE_FALLBACKS),
        ] {
            assert!(
                fallbacks.is_empty(),
                "{name} still falls back to stone: {fallbacks:?}"
            );
        }
        println!("1.8 stone fallbacks: {}", gen::v1_8::STONE_FALLBACKS.len());
    }

    #[test]
    fn the_legacy_table_round_trips_the_common_blocks() {
        use aether_api::block_ids as b;
        assert_eq!(V1_8.vanilla(b::AIR), 0);
        assert_eq!(V1_8.vanilla(b::STONE), 1);
        assert_eq!(V1_8.vanilla(b::GRASS_BLOCK), 2);
        // And the reverse names a real engine state for every id we emit.
        for (id, engine) in gen::v1_8::LEGACY_TO_ENGINE {
            assert_eq!(V1_8.engine(*id), Some(aether_world::BlockStateId(*engine)));
        }
    }
}
