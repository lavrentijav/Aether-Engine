//! Block translation and substitution across protocol versions (J1 + J2).
//!
//! The engine's [`BlockStateId`]s are vanilla 1.21.11's flattened state ids. A
//! client on another release has its own numbering and, for anything added
//! since, no block with that name at all. This module answers one question:
//! *what state does this engine block have on that client?*
//!
//! Two steps, both resolved ahead of time so the wire path is a single array
//! read:
//!
//! 1. **Translation.** The same block in the client's version, by name and
//!    properties ([`BlockTable`]). A property the version lacks takes the
//!    version's default for that block.
//! 2. **Substitution.** A block the version never had becomes the closest thing
//!    it does have — same shape and properties where one exists
//!    (`pale_oak_stairs` → `oak_stairs`, `copper_bulb` → `copper_block`), and
//!    only as a last resort stone. The rules live in
//!    `tools/gen/compat/blocks.json` and are resolved at generation time.
//!
//! The tables are generated by `tools/gen/compat/gen.js` from PrismarineJS
//! `minecraft-data` — the same source the engine's own registry is pinned to.
//! Each carries the list of blocks that still fall back to stone
//! (`STONE_FALLBACKS`) so a regression is visible rather than silent; see
//! `docs/KNOWN_ISSUES.md`.
//!
//! A substitute is a disguise: it changes only what the client sees. The
//! server's world and every action the client sends still refer to the real
//! engine block.
//!
//! # Reusing the rules for block items
//!
//! An item that places a block (a "block item") follows that block's
//! substitution: if `pale_oak_stairs` becomes `oak_stairs` on a client, so does
//! the item of the same name. The rules are in
//! `tools/gen/compat/blocks.json`, and `tools/gen/compat/gen.js` exposes the
//! resolver (`resolver`) that applies them (`from` with a single `*` wildcard,
//! chained through a target that is itself missing) — the item tables the items
//! layer generates reuse exactly that file and that resolver.

use aether_world::BlockStateId;

use super::gen;

/// A flattened-state version's block table: engine state → the version's state.
///
/// The runs are sorted by their first engine state and cover the whole engine
/// state space, so a lookup is a binary search and one addition — no schema, no
/// name compare. An id past the table is a modded block and takes the version's
/// stone.
#[derive(Clone, Copy)]
pub struct BlockTable {
    /// `(first engine state, run length, first version state)`.
    pub runs: &'static [(u32, u32, u32)],
    /// The version's own stone default state.
    pub stone: u32,
}

impl BlockTable {
    /// The client's state id for an engine state.
    #[inline]
    pub fn state(&self, id: BlockStateId) -> u32 {
        let raw = id.raw();
        let i = self.runs.partition_point(|r| r.0 <= raw);
        match i.checked_sub(1).and_then(|i| self.runs.get(i)) {
            Some(&(start, len, to)) if raw < start + len => to + (raw - start),
            // Past the generated table (a modded block) or a gap: stone, an
            // id the client has, rather than one it would reject.
            _ => self.stone,
        }
    }
}

/// A pre-flattening version's table: engine state → its `(id << 4)` value.
///
/// 1.8.9 predates flattened states and stores `(block_id << 4) | meta`. The
/// data has no metadata table, so a variant lands on its block's default meta;
/// see [`V1_8`].
#[derive(Clone, Copy)]
pub struct LegacyTable {
    /// `(first engine state, run length, legacy block id)`.
    pub runs: &'static [(u32, u32, u16)],
    /// `(legacy block id, engine default state)`, sorted by id.
    pub reverse: &'static [(u16, u32)],
    /// The version's stone id.
    pub stone: u16,
}

impl LegacyTable {
    /// The legacy numeric block id for an engine state.
    #[inline]
    pub fn vanilla(&self, id: BlockStateId) -> u16 {
        let raw = id.raw();
        let i = self.runs.partition_point(|r| r.0 <= raw);
        match i.checked_sub(1).and_then(|i| self.runs.get(i)) {
            Some(&(start, len, to)) if raw < start + len => to,
            _ => self.stone,
        }
    }

    /// The engine state a legacy block id names, if the engine has that block.
    #[inline]
    pub fn engine(&self, vanilla: u16) -> Option<BlockStateId> {
        self.reverse
            .binary_search_by_key(&vanilla, |r| r.0)
            .ok()
            .map(|i| BlockStateId(self.reverse[i].1))
    }
}

/// One table per flattened release, oldest first. The module doc and each
/// static name give the protocol id it serves.
macro_rules! flat {
    ($name:ident, $m:ident) => {
        pub static $name: BlockTable = BlockTable {
            runs: gen::$m::STATE_RUNS,
            stone: gen::$m::STONE,
        };
    };
}

