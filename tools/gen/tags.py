#!/usr/bin/env python3
"""Generate crates/aether-server/src/protocol/v774/tags.rs.

Usage: tags.py <data/minecraft dir of a 1.21.11 data pack> <reports/registries.json>

Resolves every tag of the static registries (nested `#tag` references and
all) to the protocol ids the client numbers those registries by, so the
server can send the "Update Tags" packet without the game's files at run
time.
"""
import json, os, sys

data, reports = sys.argv[1], sys.argv[2]
regs = json.load(open(reports))
DIRS = {
    "minecraft:block": "block",
    "minecraft:item": "item",
    "minecraft:fluid": "fluid",
    "minecraft:entity_type": "entity_type",
    "minecraft:game_event": "game_event",
}

out = ["//! Vanilla 1.21.11 tags of the static registries, resolved to protocol ids.",
       "//! Generated by `tools/gen/tags.py` from the game's data pack and",
       "//! `registries.json` report. Do not edit by hand.",
       "",
       "/// `(registry, [(tag, [protocol id])])`.",
       "pub static TAGS: &[(&str, &[(&str, &[u32])])] = &["]
for reg, sub in DIRS.items():
    ids = {k: v["protocol_id"] for k, v in regs[reg]["entries"].items()}
    root = os.path.join(data, "tags", sub)
    raw = {}
    for dirpath, _, files in os.walk(root):
        for f in files:
            if f.endswith(".json"):
                rel = os.path.relpath(os.path.join(dirpath, f), root)[:-5].replace(os.sep, "/")
                raw["minecraft:" + rel] = json.load(open(os.path.join(dirpath, f)))["values"]
    memo = {}
    def resolve(tag, seen=()):
        if tag in memo:
            return memo[tag]
        acc = []
        for v in raw.get(tag, []):
            req = True
            if isinstance(v, dict):
                req = v.get("required", True)
                v = v["id"]
            if v.startswith("#"):
                acc += resolve(v[1:], seen + (tag,))
            elif v in ids:
                acc.append(ids[v])
            elif req:
                print(f"warning: {tag} names unknown {v}", file=sys.stderr)
        res = sorted(set(acc))
        memo[tag] = res
        return res
    out.append(f'    ("{reg}", &[')
    for tag in sorted(raw):
        vals = ", ".join(map(str, resolve(tag)))
        out.append(f'        ("{tag}", &[{vals}]),')
    out.append("    ]),")
out.append("];")
print("\n".join(out))
