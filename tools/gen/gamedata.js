// Generates crates/aether-server/src/game/data.rs from PrismarineJS
// minecraft-data (pc/1.21.11). Run from tools/probe (where mineflayer, and so
// minecraft-data, is installed):
//
//   node ../gen/gamedata.js > ../../crates/aether-server/src/game/data.rs
//
// The output is checked in; this script only needs re-running when the data
// version changes.
const d = require(require.resolve('minecraft-data', { paths: [process.cwd()] }))('1.21.11')
const q = n => JSON.stringify('minecraft:' + n)
const f = x => (Number.isInteger(x) ? x.toFixed(1) : String(x))
const itemName = id => d.items[id] && d.items[id].name
const out = []
const w = s => out.push(s)

w('//! Game data tables, generated by `tools/gen/gamedata.js` from PrismarineJS')
w('//! `minecraft-data` (pc/1.21.11, MIT). Do not edit by hand.')
w('#![allow(clippy::all)]')
w('')
w('use super::tables::{Food, LootDrop, Shaped, Shapeless};')
w('')

// --- Items: (name, max stack, max durability), sorted by name.
const items = d.itemsArray.slice().sort((a, b) => (a.name < b.name ? -1 : 1))
w(`pub static ITEMS: [(&str, u8, u16); ${items.length}] = [`)
for (const it of items) w(`    (${q(it.name)}, ${it.stackSize}, ${it.maxDurability || 0}),`)
w('];')
w('')

// --- Foods: nutrition from the data; saturation from vanilla's food
// properties (the data's own saturation fields are not in vanilla's units).
const SAT = { apple: 2.4, baked_potato: 6.0, beef: 1.8, beetroot: 1.2, beetroot_soup: 7.2, bread: 6.0, carrot: 3.6, chicken: 1.2, cod: 0.4, cooked_beef: 12.8, cooked_chicken: 7.2, cooked_cod: 6.0, cooked_mutton: 9.6, cooked_porkchop: 12.8, cooked_rabbit: 6.0, cooked_salmon: 9.6, cookie: 0.4, dried_kelp: 0.6, enchanted_golden_apple: 9.6, golden_apple: 9.6, golden_carrot: 14.4, honey_bottle: 1.2, melon_slice: 1.2, mushroom_stew: 7.2, mutton: 1.2, poisonous_potato: 1.2, porkchop: 1.8, potato: 0.6, pufferfish: 0.2, pumpkin_pie: 4.8, rabbit: 1.8, rabbit_stew: 12.0, rotten_flesh: 0.8, salmon: 0.4, spider_eye: 3.2, suspicious_stew: 7.2, sweet_berries: 0.4, glow_berries: 0.4, tropical_fish: 0.2, chorus_fruit: 2.4 }
const foods = d.foodsArray.slice().sort((a, b) => (a.name < b.name ? -1 : 1))
w(`pub static FOODS: [(&str, Food); ${foods.length}] = [`)
for (const fd of foods) {
  const sat = SAT[fd.name] !== undefined ? SAT[fd.name] : fd.foodPoints * 1.2
  w(`    (${q(fd.name)}, Food { nutrition: ${fd.foodPoints}, saturation: ${f(+sat.toFixed(2))} }),`)
}
w('];')
w('')

// --- Blocks: hardness, mining material, tools that harvest it, and drops.
const loot = d.blockLoot
const blocks = d.blocksArray.slice().sort((a, b) => (a.name < b.name ? -1 : 1))
const drop = (it, chance, lo, hi, silk) =>
  `LootDrop { item: ${q(it)}, chance: ${f(+chance.toFixed(4))}, min: ${lo}, max: ${hi}, silk: ${silk}, player_kill: false }`
w('/// `(name, hardness (-1 unbreakable), material, harvest tools, drops)`.')
w(`pub static BLOCKS: [(&str, f32, &str, &[&str], &[LootDrop]); ${blocks.length}] = [`)
for (const b of blocks) {
  const tools = b.harvestTools ? Object.keys(b.harvestTools).map(id => q(itemName(+id))) : []
  let drops = []
  const l = loot[b.name]
  if (l && l.drops.length) {
    const hasSilk = l.drops.some(x => x.silkTouch || x.noSilkTouch)
    for (const x of l.drops) {
      if (!d.itemsByName[x.item]) continue
      const silk = x.silkTouch ? 1 : x.noSilkTouch ? -1 : 0
      // minecraft-data splits alternatives evenly; an alternative is certain
      // once its silk-touch condition holds.
      const chance = hasSilk && silk !== 0 ? 1 : x.dropChance
      drops.push(drop(x.item, chance, Math.max(1, x.stackSizeRange[0] || 1), Math.max(1, x.stackSizeRange[1] || x.stackSizeRange[0] || 1), silk))
    }
  } else {
    for (const id of b.drops || []) {
      const n = itemName(typeof id === 'object' ? id.drop : id)
      if (n) drops.push(drop(n, 1, 1, 1, 0))
    }
  }
  w(`    (${q(b.name)}, ${f(b.hardness === null ? -1 : b.hardness)}, ${JSON.stringify(b.material || 'default')}, &[${tools.join(', ')}], &[${drops.join(', ')}]),`)
}
w('];')
w('')

// --- Mining materials: tool -> speed multiplier.
const mats = Object.keys(d.materials).sort()
w(`pub static MATERIALS: [(&str, &[(&str, f32)]); ${mats.length}] = [`)
for (const m of mats) {
  const e = Object.entries(d.materials[m]).map(([id, s]) => `(${q(itemName(+id))}, ${f(s)})`)
  w(`    (${JSON.stringify(m)}, &[${e.join(', ')}]),`)
}
w('];')
w('')

// --- Entity types: (name, protocol id, width, height, category).
const ents = d.entitiesArray.slice().sort((a, b) => (a.name < b.name ? -1 : 1))
w(`pub static ENTITY_TYPES: [(&str, i32, f32, f32, &str); ${ents.length}] = [`)
for (const e of ents) w(`    (${q(e.name)}, ${e.id}, ${f(e.width)}, ${f(e.height)}, ${JSON.stringify(e.type)}),`)
w('];')
w('')

// --- Entity loot.
const el = Object.values(d.entityLoot).filter(e => d.entitiesByName[e.entity]).sort((a, b) => (a.entity < b.entity ? -1 : 1))
w(`pub static ENTITY_LOOT: [(&str, &[LootDrop]); ${el.length}] = [`)
for (const e of el) {
  const ds = e.drops.filter(x => d.itemsByName[x.item]).map(x =>
    `LootDrop { item: ${q(x.item)}, chance: ${f(+x.dropChance.toFixed(4))}, min: ${x.stackSizeRange[0] || 0}, max: ${x.stackSizeRange[1] || x.stackSizeRange[0] || 1}, silk: 0, player_kill: ${!!x.playerKill} }`)
  w(`    (${q(e.entity)}, &[${ds.join(', ')}]),`)
}
w('];')
w('')

// --- Crafting recipes.
const shaped = [], shapeless = []
for (const [rid, list] of Object.entries(d.recipes)) {
  for (const r of list) {
    const res = itemName(r.result.id)
    if (!res) continue
    if (r.inShape) {
      const h = r.inShape.length, wd = Math.max(...r.inShape.map(row => row.length))
      const cells = []
      for (const row of r.inShape) for (let i = 0; i < wd; i++) {
        const c = row[i]; cells.push(c === null || c === undefined ? '""' : q(itemName(typeof c === 'object' ? c.id : c)))
      }
      shaped.push(`    Shaped { w: ${wd}, h: ${h}, cells: &[${cells.join(', ')}], result: ${q(res)}, count: ${r.result.count} },`)
    } else if (r.ingredients) {
      const ing = r.ingredients.map(c => q(itemName(typeof c === 'object' ? c.id : c)))
      shapeless.push(`    Shapeless { ingredients: &[${ing.join(', ')}], result: ${q(res)}, count: ${r.result.count} },`)
    }
  }
}
w(`pub static SHAPED: [Shaped; ${shaped.length}] = [`); shaped.forEach(s => w(s)); w('];'); w('')
w(`pub static SHAPELESS: [Shapeless; ${shapeless.length}] = [`); shapeless.forEach(s => w(s)); w('];')
console.log(out.join('\n'))
