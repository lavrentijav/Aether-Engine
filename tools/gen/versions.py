#!/usr/bin/env python3
"""Generate the data module of one protocol version for the modern codec.

Usage:
  versions.py <module name> <reports dir of that version> <data/minecraft dir>
              <reports dir of 1.21.11> <synced registries, comma separated>
              <core pack versions, comma separated> <gen dir>  >  gen/<module>.rs

Everything is resolved from the game's own data-generator reports and data
pack, so a new release is a regeneration rather than a hand edit:

* packet ids by name, per phase and direction;
* the 1.21.11 block-state id space (the engine's own) remapped onto this
  version's, as runs of `(first engine id, length, first version id)`;
* item, entity-type, menu, data-component and particle ids by name;
* the entries of every synchronized registry, in the order they are sent;
* the tags of the static registries and of the synchronized ones;
* the overworld dimension type, as an NBT builder;
* every entry of every synchronized registry as network NBT, deflated into
  `gen/<module>.registries.z`, for a client that does not have the vanilla
  pack to fill them from (bot libraries, mostly).
"""
import json, os, struct, sys, zlib

mod, rep, data, base_rep, synced_arg, packs_arg, gen_dir = sys.argv[1:8]
synced = [s for s in synced_arg.split(",") if s]
packs = [p for p in packs_arg.split(",") if p]
regs = json.load(open(os.path.join(rep, "registries.json")))
packets = json.load(open(os.path.join(rep, "packets.json")))
out = []
w = out.append

def rid(reg):
    return {k: v["protocol_id"] for k, v in regs[reg]["entries"].items()}

w(f"//! Protocol data for {mod}, generated by `tools/gen/versions.py` from the")
w("//! game's data-generator reports and data pack. Do not edit by hand.")
w("")
w("use crate::protocol::modern::version::Packets;")
w("use crate::protocol::nbt::Nbt;")
w("")

# --- packets
fields = []
for phase, direction, prefix in [("play", "clientbound", "cb_"), ("play", "serverbound", "sb_"),
                                 ("configuration", "clientbound", "cfg_cb_"), ("configuration", "serverbound", "cfg_sb_"),
                                 ("login", "clientbound", "login_cb_"), ("login", "serverbound", "login_sb_")]:
    for name, v in packets[phase][direction].items():
        fields.append((prefix + name.split(":")[1], v["protocol_id"]))
names_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), "packet_fields.txt")
wanted = [l.strip() for l in open(names_file) if l.strip() and not l.startswith("#")]
have = dict(fields)
w("pub static PACKETS: Packets = Packets {")
for f in wanted:
    w(f"    {f}: {have.get(f, -1)},")
w("};")
w("")

# --- block states
def states(path):
    d = json.load(open(path))
    m = {}
    for name, b in d.items():
        for s in b["states"]:
            props = s.get("properties", {})
            m[name + "[" + ",".join(f"{k}={props[k]}" for k in sorted(props)) + "]"] = s["id"]
    return m
base = states(os.path.join(base_rep, "blocks.json"))
mine = states(os.path.join(rep, "blocks.json"))
runs = []
for key, i in sorted(base.items(), key=lambda x: x[1]):
    j = mine[key]
    if runs and runs[-1][0] + runs[-1][1] == i and runs[-1][2] + runs[-1][1] == j:
        runs[-1][1] += 1
    else:
        runs.append([i, 1, j])
w(f"/// `(first engine state, run length, first {mod} state)`.")
w("pub static STATE_RUNS: &[(u32, u32, u32)] = &[")
for r in runs:
    w(f"    ({r[0]}, {r[1]}, {r[2]}),")
w("];")
w(f"pub const STATE_COUNT: u32 = {len(mine)};")
w("")

def table(cname, reg):
    ids = sorted(rid(reg).items())
    w(f"pub static {cname}: &[(&str, u16)] = &[")
    for k, v in ids:
        w(f'    ("{k}", {v}),')
    w("];")
table("ITEMS", "minecraft:item")
table("ENTITY_TYPES", "minecraft:entity_type")
menus = rid("minecraft:menu"); comps = rid("minecraft:data_component_type"); parts = rid("minecraft:particle_type")
w(f"pub const MENU_GENERIC_9X3: i32 = {menus['minecraft:generic_9x3']};")
w(f"pub const MENU_GENERIC_9X6: i32 = {menus['minecraft:generic_9x6']};")
w(f"pub const MENU_CRAFTING: i32 = {menus['minecraft:crafting']};")
w(f"pub const MENU_FURNACE: i32 = {menus['minecraft:furnace']};")
w(f"pub const COMPONENT_DAMAGE: i32 = {comps['minecraft:damage']};")
w(f"pub const COMPONENT_CUSTOM_NAME: i32 = {comps['minecraft:custom_name']};")
w(f"pub const PARTICLE_EXPLOSION: i32 = {parts['minecraft:explosion']};")
w(f"pub const PARTICLE_EXPLOSION_EMITTER: i32 = {parts['minecraft:explosion_emitter']};")
w("")

# --- synced registries
def entries(reg):
    root = os.path.join(data, reg.split(":")[1])
    out_ = []
    for dp, _, fs in os.walk(root):
        for f in fs:
            if f.endswith(".json"):
                rel = os.path.relpath(os.path.join(dp, f), root)[:-5].replace(os.sep, "/")
                out_.append("minecraft:" + rel)
    return sorted(out_)
reg_entries = {r: entries(r) for r in synced}
w(f"/// Versions of the `minecraft:core` pack whose entries the client already has.")
w("pub static CORE_PACKS: &[&str] = &[" + ", ".join(f'"{p}"' for p in packs) + "];")
w("/// Every synchronized registry and its entries, in the order sent.")
w("pub static SYNCED: &[(&str, &[&str])] = &[")
for r in synced:
    w(f'    ("{r}", &[' + ", ".join(f'"{e}"' for e in reg_entries[r]) + "]),")
w("];")
w("")

# --- tags
def tag_files(sub):
    root = os.path.join(data, "tags", sub)
    raw = {}
    for dp, _, fs in os.walk(root):
        for f in fs:
            if f.endswith(".json"):
                rel = os.path.relpath(os.path.join(dp, f), root)[:-5].replace(os.sep, "/")
                raw["minecraft:" + rel] = json.load(open(os.path.join(dp, f)))["values"]
    return raw
def resolve_all(raw, ids):
    memo = {}
    def res(t, depth=0):
        if t in memo: return memo[t]
        acc = []
        for v in raw.get(t, []):
            if isinstance(v, dict): v = v["id"]
            if v.startswith("#"):
                if depth < 32: acc += res(v[1:], depth + 1)
            elif v in ids: acc.append(ids[v])
        memo[t] = sorted(set(acc)); return memo[t]
    return {t: res(t) for t in sorted(raw)}
w("/// `(registry, [(tag, [network id])])`.")
w("pub static TAGS: &[(&str, &[(&str, &[u32])])] = &[")
static = {"minecraft:block": "block", "minecraft:item": "item", "minecraft:fluid": "fluid",
          "minecraft:entity_type": "entity_type", "minecraft:game_event": "game_event"}
groups = [(r, sub, rid(r)) for r, sub in static.items()]
groups += [(r, r.split(":")[1], {e: i for i, e in enumerate(reg_entries[r])}) for r in synced]
for r, sub, ids in groups:
    tags = resolve_all(tag_files(sub), ids)
    if not tags: continue
    w(f'    ("{r}", &[')
    for t, v in tags.items():
        w(f'        ("{t}", &[' + ", ".join(map(str, v)) + "]),")
    w("    ]),")
w("];")
w("")

# --- overworld dimension type
def nbt(v):
    if isinstance(v, bool): return f"Nbt::Byte({int(v)})"
    if isinstance(v, int): return f"Nbt::Int({v})"
    if isinstance(v, float): return f"Nbt::Double({v!r})"
    if isinstance(v, str): return f"Nbt::Str({json.dumps(v)}.into())"
    if isinstance(v, list): return "Nbt::List(vec![" + ", ".join(nbt(x) for x in v) + "])"
    return "Nbt::Compound(vec![" + ", ".join(f"({json.dumps(k)}.into(), {nbt(x)})" for k, x in v.items()) + "])"
dim = json.load(open(os.path.join(data, "dimension_type", "overworld.json")))
w("/// The vanilla overworld dimension type; the codec overrides its height.")
w("pub fn overworld() -> Nbt {")
w("    " + nbt(dim))
w("}")

# --- every synced entry as network NBT
# JSON maps onto NBT the way the game's own JsonOps -> NbtOps conversion
# reads back: integers as Int, other numbers as Double, booleans as Byte. A
# list whose elements differ in type is written the 1.21.5 way, each element
# wrapped in a compound under the empty key.
def tag_of(v):
    if isinstance(v, bool): return 1
    if isinstance(v, int): return 3
    if isinstance(v, float): return 6
    if isinstance(v, str): return 8
    if isinstance(v, list): return 9
    return 10
def mutf8(t):
    b = t.encode("utf-8")
    return struct.pack(">H", len(b)) + b
def payload(v):
    t = tag_of(v)
    if t == 1: return struct.pack(">b", int(v))
    if t == 3:
        if -2**31 <= v < 2**31: return struct.pack(">i", v)
        return struct.pack(">d", float(v))
    if t == 6: return struct.pack(">d", v)
    if t == 8: return mutf8(v)
    if t == 9:
        types = {tag_of(x) for x in v}
        if types <= {3, 6} and len(types) == 2:
            v, types = [float(x) for x in v], {6}
        if types == {3} and any(not (-2**31 <= x < 2**31) for x in v):
            v, types = [float(x) for x in v], {6}
        if len(types) > 1:
            v, types = [{"": x} for x in v], {10}
        et = types.pop() if types else 0
        return bytes([et]) + struct.pack(">i", len(v)) + b"".join(payload(x) for x in v)
    body = b""
    for k, x in v.items():
        tt = tag_of(x)
        if tt == 3 and not (-2**31 <= x < 2**31): tt = 6
        body += bytes([tt]) + mutf8(k) + payload(x)
    return body + b"\x00"
# Biome fields only the generator reads; the network codec ignores them.
WORLDGEN_ONLY = {"features", "carvers", "spawners", "spawn_costs"}
blob = b""
for r in synced:
    for e in reg_entries[r]:
        d = json.load(open(os.path.join(data, r.split(":")[1], e.split(":", 1)[1] + ".json")))
        if r == "minecraft:worldgen/biome":
            d = {k: x for k, x in d.items() if k not in WORLDGEN_ONLY}
        n = bytes([tag_of(d)]) + payload(d)
        blob += struct.pack(">I", len(n)) + n
ident = "v" + mod.replace(".", "_")
if synced:
    open(os.path.join(gen_dir, ident + ".registries.z"), "wb").write(zlib.compress(blob, 9))
    w("/// Every entry of `SYNCED`, in order, as length-prefixed network NBT, deflated.")
    w(f'pub static REGISTRY_DATA: &[u8] = include_bytes!("{ident}.registries.z");')
else:
    w("pub static REGISTRY_DATA: &[u8] = &[];")
print("\n".join(out))
