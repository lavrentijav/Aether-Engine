// Generates crates/aether-world/src/registry/shapes.rs — the per-block-state
// collision boxes — from PrismarineJS `minecraft-data` (pc/1.21.11), the same
// source and the same block order `registry/blocks.rs` was generated from.
//
// Run from a directory where `minecraft-data` resolves (tools/probe, after
// `npm install`, or any scratch dir that has it):
//
//   node tools/gen/collisions.js > crates/aether-world/src/registry/shapes.rs
//
// The output is checked in; re-run only when the data version is re-pinned.
//
// `blockCollisionShapes.json` publishes two maps: `shapes` (a shape id ->
// list of boxes) and `blocks` (a block name -> either one shape id, shared by
// every state, or a list with one shape id per state, in the block's own
// state order). The engine's `BlockStateId` **is** the vanilla flattened
// state id, in the same block order, so the global state id is
// `block.minStateId + offset` and the per-state shape ids drop straight into
// `STATE_SHAPE`. A shape id no state references would be dead weight, but the
// data has none, so they are kept as-is and indexed directly.
const path = require('path')
const d = require(require.resolve('minecraft-data', { paths: [process.cwd(), path.join(__dirname, '..', 'probe')] }))('1.21.11')
const blocks = d.blocksArray // vanilla block order, `id` == index
const shapeById = d.blockCollisionShapes.shapes
const shapeOfBlock = d.blockCollisionShapes.blocks
const expectedStates = 29671

const out = []
const w = s => out.push(s)
const f = x => {
  const s = String(x)
  return Number.isInteger(x) ? x.toFixed(1) : s
}

// --- Validate the assumptions the engine relies on, so a bad regen fails here
// rather than as a silently wrong collision table.
let stateTotal = 0
const shapeCount = Object.keys(shapeById).length
const usedShape = new Set()
for (const b of blocks) {
  if (b.minStateId !== stateTotal) {
    throw new Error(`block ${b.name}: minStateId ${b.minStateId} != running total ${stateTotal}`)
  }
  const v = shapeOfBlock[b.name]
  const n = b.maxStateId - b.minStateId + 1
  // A scalar means every state of the block shares one shape; a list must
  // have exactly one entry per state.
  if (Array.isArray(v) && v.length !== n) throw new Error(`${b.name}: ${v.length} shapes for ${n} states`)
  if (Array.isArray(v)) v.forEach(s => usedShape.add(s))
  else usedShape.add(v)
  stateTotal = b.maxStateId + 1
}
if (stateTotal !== expectedStates) throw new Error(`state total ${stateTotal} != ${expectedStates}`)
if (usedShape.size !== shapeCount) {
  throw new Error(`${shapeCount - usedShape.size} shape ids are unreferenced`)
}

// --- Header.
w('//! Per-block-state collision boxes for vanilla 1.21.11.')
w('//!')
w('//! Generated by `tools/gen/collisions.js` from PrismarineJS `minecraft-data`')
w('//! `pc/1.21.11/blockCollisionShapes.json` (MIT). Do not edit by hand.')
w('//!')
w('//! `STATE_PROPS` in [`super::blocks`] carries a single `collision` flag per')
w('//! *block*, because `minecraft-data` publishes bounding boxes per block. The')
w('//! boxes below are the exception that flag cannot express: an **open** door or')
w('//! fence gate has no collision at all, a **top** slab sits in the upper half of')
w('//! its cell, a fence is a 1.5-tall shape rather than a cube. Physics reads')
w('//! these; everything that only needs "is there something here" keeps using the')
w('//! mask.')
w('')
w('/// One collision box in block-local coordinates:')
w('/// `[min_x, min_y, min_z, max_x, max_y, max_z]`, each in units of one block.')
w('pub type Box6 = [f32; 6];')
w('')
w(`/// The distinct collision shapes, indexed by vanilla shape id (${shapeCount}).`)
w(`/// Shape 0 is the empty shape: air, water and every open door or gate.`)
w('#[rustfmt::skip]')
w(`pub static SHAPES: &[&[Box6]] = &[`)
for (let i = 0; i < shapeCount; i++) {
  const boxes = shapeById[i] || []
  const body = boxes.map(bx => `[${bx.map(f).join(', ')}]`).join(', ')
  w(`    &[${body}],`)
}
w('];')
w('')

// --- The state -> shape map.
w(`/// The shape index of every block state, indexed by vanilla flattened state id`)
w(`/// (\`0..=${stateTotal - 1}\`), the engine's own [\`crate::BlockStateId\`].`)
w('#[rustfmt::skip]')
w(`pub static STATE_SHAPE: [u16; ${stateTotal}] = [`)
let row = []
const flush = () => {
  if (row.length) {
    w('    ' + row.join(', ') + ',')
    row = []
  }
}
for (const b of blocks) {
  const v = shapeOfBlock[b.name]
  const n = b.maxStateId - b.minStateId + 1
  for (let k = 0; k < n; k++) {
    row.push(Array.isArray(v) ? v[k] : v)
    if (row.length === 24) flush()
  }
}
flush()
w('];')
w('')

// --- Accessors.
w('/// The collision boxes of a block state, in block-local coordinates.')
w('///')
w('/// An unknown state (a modded block id, or a state past the table) has no')
w('/// boxes, the safe answer: it can never become an invisible wall.')
w('#[inline]')
w('pub fn collision_boxes(state: u32) -> &\'static [Box6] {')
w('    match STATE_SHAPE.get(state as usize) {')
w('        Some(&s) => SHAPES[s as usize],')
w('        None => &[],')
w('    }')
w('}')
w('')
w('/// Whether a block state has any collision box at all.')
w('#[inline]')
w('pub fn collides(state: u32) -> bool {')
w('    !collision_boxes(state).is_empty()')
w('}')

process.stdout.write(out.join('\n') + '\n')
