'use strict'
// Generates per-release gameplay data for the older codecs (queue J, task J9).
//
//   node tools/gen/gen_legacy_play.js > crates/aether-server/src/protocol/modern/legacy_gen.rs
//
// Reads PrismarineJS `minecraft-data` (installed under `tools/probe`, as the
// other generators do) plus the modern 1.21.11 packet table already checked
// in, so the modern field names can be translated to minecraft-data's own
// packet names by matching ids rather than by a hand-kept alias table.
const fs = require('fs')
const path = require('path')
const d = require(require.resolve('minecraft-data', {
  paths: [process.cwd(), path.join(__dirname, '..', 'probe')],
}))

const ROOT = path.join(__dirname, '..', '..')
const modern = fs.readFileSync(
  path.join(ROOT, 'crates/aether-server/src/protocol/modern/gen/v1_21_11.rs'), 'utf8')
const modernIds = {}
for (const m of modern.matchAll(/^\s*([a-z][a-z0-9_]*): (-?\d+),/gm)) modernIds[m[1]] = +m[2]

// modern field -> minecraft-data packet name, derived by matching the 1.21.11
// ids: the modern module's field ids are the canonical game ids.
const base = d('1.21.11')
function mappings(version, phase, dir) {
  try {
    const t = version.protocol[phase][dir].types.packet
    return t[1][0].type[1].mappings
  } catch (e) { return {} }
}
const baseMaps = {
  cb: mappings(base, 'play', 'toClient'),
  sb: mappings(base, 'play', 'toServer'),
  cfg_cb: mappings(base, 'configuration', 'toClient'),
  cfg_sb: mappings(base, 'configuration', 'toServer'),
  login_cb: mappings(base, 'login', 'toClient'),
  login_sb: mappings(base, 'login', 'toServer'),
}
const byId = {}
for (const [k, m] of Object.entries(baseMaps)) {
  byId[k] = {}
  for (const [id, name] of Object.entries(m)) byId[k][parseInt(id, 16)] = name
}
const phaseOf = field => field.startsWith('cfg_cb_') ? 'cfg_cb'
  : field.startsWith('cfg_sb_') ? 'cfg_sb'
  : field.startsWith('login_cb_') ? 'login_cb'
  : field.startsWith('login_sb_') ? 'login_sb'
  : field.startsWith('cb_') ? 'cb' : 'sb'
const fieldName = {}
for (const field of Object.keys(modernIds)) {
  const id = modernIds[field]
  fieldName[field] = id < 0 ? null : (byId[phaseOf(field)][id] || null)
}
// The one old-only packet the modern table does not have.
fieldName['cb_entity_teleport'] = 'entity_teleport'

const RELEASES = [
  ['v1_20_5', '1.20.5', 766],
  ['v1_21_1', '1.21.1', 767],
  ['v1_21_3', '1.21.3', 768],
  ['v1_21_4', '1.21.4', 769],
  ['v1_21_5', '1.21.5', 770],
  ['v1_21_6', '1.21.6', 771],
  ['v1_21_8', '1.21.8', 772],
  ['v1_21_9', '1.21.9', 773],
]

// The menu registry (Minecraft's own `MenuType` order). The crafter menu did
// not exist before 1.21, so 1.20.5's entries after `generic_3x3` are one lower.
function menus(release) {
  const shift = release === 'v1_20_5' ? -1 : 0
  return {
    generic_9x3: 2,
    generic_9x6: 5,
    generic_3x3: 6,
    crafting: 12 + shift,
    furnace: 14 + shift,
    hopper: 16 + shift,
  }
}

const w = []
const o = s => w.push(s)
o('//! Generated gameplay data for the older codecs (queue J, task J9).')
o('//!')
o('//! Generated by `tools/gen/gen_legacy_play.js` from PrismarineJS')
o('//! `minecraft-data`; do not edit by hand. One module per protocol 766-773,')
o('//! carrying the packet ids, entity types, damage types, menu ids and item')
o('//! data-component ids that the shared gameplay path needs. Block and item')
o('//! tables come from `protocol::compat` instead.')
o('')
o('use super::version::Packets;')
o('')

for (const [mod, ver, proto] of RELEASES) {
  const v = d(ver)
  const maps = {
    cb: mappings(v, 'play', 'toClient'),
    sb: mappings(v, 'play', 'toServer'),
    cfg_cb: mappings(v, 'configuration', 'toClient'),
    cfg_sb: mappings(v, 'configuration', 'toServer'),
    login_cb: mappings(v, 'login', 'toClient'),
    login_sb: mappings(v, 'login', 'toServer'),
  }
  const idOf = (phase, name) => {
    if (name == null) return -1
    for (const [id, n] of Object.entries(maps[phase])) if (n === name) return parseInt(id, 16)
    return -1
  }

  o(`/// ${ver}, protocol ${proto}.`)
  o(`pub mod ${mod} {`)
  o('    use super::Packets;')
  o('')
  o('    pub static PACKETS: Packets = Packets {')
  for (const f of Object.keys(modernIds)) o(`        ${f}: ${idOf(phaseOf(f), fieldName[f])},`)
  o('    };')
  o('')

  const ents = v.entitiesArray
    .map(e => ['minecraft:' + e.name, e.id])
    .sort((a, b) => (a[0] < b[0] ? -1 : 1))
  o('    pub static ENTITY_TYPES: &[(&str, u16)] = &[')
  for (const [n, i] of ents) o(`        ("${n}", ${i}),`)
  o('    ];')
  o('')

  // Damage types in *registry order* (the wire id is the index), read from the
  // codec's own registry dump — minecraft-data's login packet sorts its
  // entries alphabetically and so cannot give the order.
  const reg = fs.readFileSync(
    path.join(ROOT, `crates/aether-server/src/protocol/v${proto}/registry.rs`), 'utf8')
  const dts = [...reg.matchAll(/^\s*\("([a-z0-9_]+)", "[A-Za-z]+", (?:ALIVE|ALWAYS), [0-9.]+\),/gm)]
    .map(m => 'minecraft:' + m[1])
  o('    /// Damage-type names in registry order; the index is the wire id.')
  o('    pub static DAMAGE_TYPES: &[&str] = &[' + dts.map(s => `"${s}"`).join(', ') + '];')
  o('')

  const comps = {}
  const sct = v.protocol.types['SlotComponentType']
  for (const [id, n] of Object.entries(sct[1].mappings)) comps[n] = parseInt(id)
  o(`    pub const COMPONENT_DAMAGE: i32 = ${comps['damage']};`)
  o(`    pub const COMPONENT_CUSTOM_NAME: i32 = ${comps['custom_name']};`)
  o(`    pub const COMPONENT_LORE: i32 = ${comps['lore']};`)
  o('')

  // Engine attribute id (1.21.11 order) -> this version's attribute id, by
  // name. Attributes were reordered, not appended, between releases.
  const findMap = (o, pred) => {
    if (Array.isArray(o)) {
      for (const x of o) { const r = findMap(x, pred); if (r) return r }
    } else if (o && typeof o === 'object') {
      if (o.mappings && pred(o.mappings)) return o.mappings
      for (const x of Object.values(o)) { const r = findMap(x, pred); if (r) return r }
    }
    return null
  }
  const attrOf = (version) => {
    const t = version.protocol.play.toClient.types.packet_entity_update_attributes
    const m = findMap(t, v => Object.values(v).some(n => n === 'generic.movement_speed'))
    const byId = [], byName = {}
    for (const [id, n] of Object.entries(m)) {
      byId[parseInt(id)] = n
      byName[n] = parseInt(id)
    }
    return { byId, byName }
  }
  const baseAttr = attrOf(base)
  const mineAttr = attrOf(v)
  const attrMap = []
  for (let id = 0; id < baseAttr.byId.length; id++) {
    const name = baseAttr.byId[id]
    attrMap.push(name !== undefined && mineAttr.byName[name] !== undefined ? mineAttr.byName[name] : -1)
  }
  o('    /// Engine attribute id (1.21.11 order) -> this version\'s id; -1 absent.')
  o('    pub static ATTRIBUTE_MAP: &[i32] = &[' + attrMap.join(', ') + '];')
  o('')

  const m = menus(mod)
  o(`    pub const MENU_GENERIC_9X3: i32 = ${m.generic_9x3};`)
  o(`    pub const MENU_GENERIC_9X6: i32 = ${m.generic_9x6};`)
  o(`    pub const MENU_GENERIC_3X3: i32 = ${m.generic_3x3};`)
  o(`    pub const MENU_CRAFTING: i32 = ${m.crafting};`)
  o(`    pub const MENU_FURNACE: i32 = ${m.furnace};`)
  o(`    pub const MENU_HOPPER: i32 = ${m.hopper};`)
  o('')
  o('    pub const PARTICLE_EXPLOSION: i32 = 0;')
  o('    pub const PARTICLE_EXPLOSION_EMITTER: i32 = 0;')
  o('}')
  o('')
}
process.stdout.write(w.join('\n'))
